#!/usr/bin/env python3
"""Generates emu/launcherfont_sans.inc: anti-aliased proportional glyphs (ASCII 0x20-0x7E) for the chooser and the start-up notice, rendered from
Liberation Sans (SIL Open Font License). Three faces: body 16 px, bold 16 px, large 26 px.   python3 tools/make_launcher_sans.py"""
import os
from PIL import Image, ImageDraw, ImageFont
here = os.path.dirname(os.path.abspath(__file__))
D = "/usr/share/fonts/truetype/liberation/"
FACES = [("body", "LiberationSans-Regular.ttf", 16), ("bold", "LiberationSans-Bold.ttf", 16), ("big", "LiberationSans-Regular.ttf", 26)]
out = ["// generated by tools/make_launcher_sans.py from Liberation Sans (SIL Open Font License); anti-aliased glyphs, ASCII 0x20-0x7E\n"]
for name, fn, size in FACES:
    f = ImageFont.truetype(D + fn, size); asc, desc = f.getmetrics(); H = asc + desc + 1
    glyphs = []
    for c in range(0x20, 0x7F):
        adv = max(2, round(f.getlength(chr(c)))); w = adv + 2
        im = Image.new("L", (w, H), 0); ImageDraw.Draw(im).text((1, 0), chr(c), font=f, fill=255)
        glyphs.append((adv, w, im))
    aw = sum(g[1] for g in glyphs)
    atlas = Image.new("L", (aw, H), 0); x = 0; xs = []
    for adv, w, im in glyphs: atlas.paste(im, (x, 0)); xs.append(x); x += w
    px = atlas.tobytes()
    out.append("static const unsigned char pf_%s_px[%d] = {\n" % (name, len(px)))
    for i in range(0, len(px), 32): out.append("  " + ",".join(str(b) for b in px[i:i + 32]) + ",\n")
    out.append("};\n")
    out.append("static const unsigned short pf_%s_x[95] = {%s};\nstatic const unsigned char pf_%s_adv[95] = {%s};\n" % (name, ",".join(map(str, xs)), name, ",".join(str(g[0]) for g in glyphs)))
    out.append("#define PF_%s_H %d\n#define PF_%s_AW %d\n" % (name.upper(), H, name.upper(), aw))
open(os.path.join(here, "..", "emu", "launcherfont_sans.inc"), "w").write("".join(out))
print("wrote emu/launcherfont_sans.inc")
