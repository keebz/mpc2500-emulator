#!/usr/bin/env python3
"""Generate emu/cgrom.inc: an 8x8 ASCII font standing in for the T6963C's internal CG ROM.
The real chip's glyph shapes are not available to us, so this is an approximation used only when firmware enables the
controller's text layer (the stock OS draws everything as graphics). Code n (0..0x5F) is ASCII 0x20+n; the rest is blank."""
import sys
from PIL import Image, ImageDraw, ImageFont
font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf", 9)
rows = []
for code in range(128):
    ch = chr(0x20 + code) if code < 0x5F else " "
    im = Image.new("L", (8, 8), 0)
    ImageDraw.Draw(im).text((0, -1), ch, fill=255, font=font)
    glyph = []
    for y in range(8):
        b = 0
        for x in range(8):
            if im.getpixel((x, y)) > 110: b |= 0x80 >> x
        glyph.append(b)
    rows.append(glyph)
out = open(sys.argv[1] if len(sys.argv) > 1 else "emu/cgrom.inc", "w")
out.write("// generated by tools/make_cgrom.py - approximation of the T6963C internal CG ROM (code n = ASCII 0x20+n)\n")
for code, g in enumerate(rows):
    out.write("    {" + ",".join("0x%02X" % b for b in g) + "},\n")
