#!/usr/bin/env python3
"""Generates emu/launcherfont.inc: a 8x16 bitmap font (ASCII 0x20-0x7F) for the launcher window, rendered from Liberation Mono (SIL OFL).
  python3 tools/make_launcher_font.py"""
import os
from PIL import Image, ImageDraw, ImageFont
here = os.path.dirname(os.path.abspath(__file__))
font = ImageFont.truetype("/usr/share/fonts/truetype/liberation/LiberationMono-Regular.ttf", 14)
rows = []
for c in range(0x20, 0x80):
    im = Image.new("L", (8, 16), 0); d = ImageDraw.Draw(im); d.fontmode = "1"
    d.text((0, -1), chr(c) if c < 0x7F else " ", font=font, fill=255)
    px = im.load(); rows.append([sum((1 << (7 - x)) for x in range(8) if px[x, y] > 127) for y in range(16)])
with open(os.path.join(here, "..", "emu", "launcherfont.inc"), "w") as f:
    f.write("// generated by tools/make_launcher_font.py from Liberation Mono (SIL Open Font License); 8x16 glyphs, ASCII 0x20-0x7F\n")
    for r in rows: f.write("    {" + ",".join("0x%02X" % b for b in r) + "},\n")
print("wrote emu/launcherfont.inc")
